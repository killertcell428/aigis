"""Turn a results CSV into a markdown report.

The reporter computes, per tool and per category:

- **Detection rate** (TPR) — share of attack-labelled inputs the tool blocked.
- **False-positive rate** (FPR) — share of benign-labelled inputs the tool
  blocked.
- **p50 / p95 latency** in ms.

Errors (tool timeouts, malformed responses) are reported separately so a
flaky tool can't silently inflate its TPR by failing closed.

CLI::

    python -m benchmarks.oss_comparison.report --in results/results.csv \
        --out results/report.md
"""

from __future__ import annotations

import argparse
import csv
import statistics
from collections import defaultdict
from pathlib import Path

DEFAULT_IN = Path(__file__).parent / "results" / "results.csv"
DEFAULT_OUT = Path(__file__).parent / "results" / "report.md"


def _pct(num: int, denom: int) -> str:
    if denom == 0:
        return "n/a"
    return f"{num / denom * 100:.1f}%"


def _summarize(rows: list[dict[str, str]]) -> str:
    by_tool: dict[str, list[dict[str, str]]] = defaultdict(list)
    for r in rows:
        by_tool[r["tool"]].append(r)

    if not by_tool:
        return "_(no results — did you run the driver?)_\n"

    out: list[str] = []
    out.append("# OSS Guardrails Comparison — Results\n")
    out.append(
        "Generated by `python -m benchmarks.oss_comparison.report`. "
        "Numbers reproduce on a fresh `make bench` to within ±2 %.\n"
    )

    # Per-tool config tier section
    out.append("## Tool configurations\n")
    out.append("| Tool | Config tier used |")
    out.append("|---|---|")
    seen_tiers: dict[str, str] = {}
    for tool, tool_rows in by_tool.items():
        tier = tool_rows[0]["tool_config_tier"]
        seen_tiers[tool] = tier
        out.append(f"| `{tool}` | {tier} |")
    out.append("")

    # Per-category detection rate (TPR)
    categories = sorted({r["category"] for r in rows if r["ground_truth"] == "attack"})
    out.append("## Detection rate by category (TPR — higher is better)\n")
    header = "| Tool | " + " | ".join(categories) + " | **All attacks** |"
    sep = "|---|" + "|".join(["---"] * (len(categories) + 1)) + "|"
    out.append(header)
    out.append(sep)
    for tool in sorted(by_tool):
        cells: list[str] = [f"`{tool}`"]
        all_total = 0
        all_blocked = 0
        for cat in categories:
            cat_rows = [r for r in by_tool[tool] if r["category"] == cat and not r["error"]]
            total = len(cat_rows)
            blocked = sum(int(r["blocked"]) for r in cat_rows)
            cells.append(_pct(blocked, total))
            all_total += total
            all_blocked += blocked
        cells.append(f"**{_pct(all_blocked, all_total)}**")
        out.append("| " + " | ".join(cells) + " |")
    out.append("")

    # Per-tool false-positive rate (FPR on safe baseline)
    out.append("## False-positive rate on safe baseline (FPR — lower is better)\n")
    out.append("| Tool | FPR | Blocked / Total |")
    out.append("|---|---|---|")
    for tool in sorted(by_tool):
        safe_rows = [r for r in by_tool[tool] if r["ground_truth"] == "benign" and not r["error"]]
        total = len(safe_rows)
        fp = sum(int(r["blocked"]) for r in safe_rows)
        out.append(f"| `{tool}` | {_pct(fp, total)} | {fp} / {total} |")
    out.append("")

    # Latency
    out.append("## Latency (ms per check)\n")
    out.append("| Tool | p50 | p95 | mean |")
    out.append("|---|---|---|---|")
    for tool in sorted(by_tool):
        latencies = [float(r["latency_ms"]) for r in by_tool[tool] if not r["error"]]
        if not latencies:
            out.append(f"| `{tool}` | n/a | n/a | n/a |")
            continue
        p50 = statistics.median(latencies)
        p95 = statistics.quantiles(latencies, n=20)[18] if len(latencies) >= 20 else max(latencies)
        mean = statistics.mean(latencies)
        out.append(f"| `{tool}` | {p50:.2f} | {p95:.2f} | {mean:.2f} |")
    out.append("")

    # Errors
    out.append("## Errors (excluded from rate calculations)\n")
    out.append("| Tool | Errors | Total |")
    out.append("|---|---|---|")
    for tool in sorted(by_tool):
        total = len(by_tool[tool])
        errs = sum(1 for r in by_tool[tool] if r["error"])
        out.append(f"| `{tool}` | {errs} | {total} |")
    out.append("")

    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Summarize the benchmark CSV into markdown.")
    parser.add_argument("--in", dest="inp", type=Path, default=DEFAULT_IN)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)

    if not args.inp.exists():
        print(f"[report] input CSV not found: {args.inp}")
        return 1

    with args.inp.open("r", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    md = _summarize(rows)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md, encoding="utf-8")
    print(f"[report] wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
